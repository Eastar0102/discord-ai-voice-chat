const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('companion', {
    start: (name) => ipcRenderer.invoke('proc:start', name),
    stop: (name) => ipcRenderer.invoke('proc:stop', name),
    startAll: () => ipcRenderer.invoke('proc:startAll'),
    guilds: () => ipcRenderer.invoke('discord:guilds'),
    join: (channelId) => ipcRenderer.invoke('discord:join', channelId),
    leave: (guildId) => ipcRenderer.invoke('discord:leave', guildId),
    setMode: (guildId, mode) => ipcRenderer.invoke('discord:mode', guildId, mode),
    talk: (guildId, text) => ipcRenderer.invoke('discord:talk', guildId, text),
    lookSources: () => ipcRenderer.invoke('look:sources'),
    lookWindows: () => ipcRenderer.invoke('look:windows'),
    lookNow: (body) => ipcRenderer.invoke('look:now', body),
    lookReading: () => ipcRenderer.invoke('look:reading'),
    lookReadUrl: (url) => ipcRenderer.invoke('look:readUrl', url),
    lookClear: () => ipcRenderer.invoke('look:clear'),
    transcribePresets: () => ipcRenderer.invoke('transcribe:presets'),
    transcribeControl: (body) => ipcRenderer.invoke('transcribe:control', body),
    inspectState: () => ipcRenderer.invoke('inspect:state'),
    inspectMemory: () => ipcRenderer.invoke('inspect:memory'),
    inspectTurns: () => ipcRenderer.invoke('inspect:turns'),
    inspectConversation: (after) => ipcRenderer.invoke('inspect:conversation', after),
    inspectMemoryMap: (layout) => ipcRenderer.invoke('inspect:memoryMap', layout),
    llmModels: () => ipcRenderer.invoke('llm:models'),
    llmSelect: (provider, model) => ipcRenderer.invoke('llm:select', provider, model),
    ttsEngines: () => ipcRenderer.invoke('tts:engines'),
    ttsSelect: (provider) => ipcRenderer.invoke('tts:select', provider),
    onLog: (cb) => ipcRenderer.on('log', (e, d) => cb(d)),
    onStatus: (cb) => ipcRenderer.on('status', (e, d) => cb(d)),
    onProcState: (cb) => ipcRenderer.on('proc-state', (e, d) => cb(d)),
});
